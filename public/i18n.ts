const CATALOG: Record<SupportedLocale, Messages> = {
  en: ENGLISH,
  "zh-CN": ZH_CN,
  "zh-TW": ZH_TW,
  ja: JA,
  ko: KO,
  es: ES,
};

const englishToKey = new Map<string, MessageKey>();
for (const [key, value] of Object.entries(ENGLISH)) {
  if (!englishToKey.has(value)) englishToKey.set(value, key as MessageKey);
}
const textSources = new WeakMap<Text, string>();
const attributeSources = new WeakMap<Element, Map<string, string>>();
const listeners = new Set<(locale: SupportedLocale) => void>();
const LOCALE_COOKIE = "bossai-funding-locale";

function normalizeLocale(value: string | null | undefined): SupportedLocale | null {
  if (!value) return null;
  const normalized = value.replace("_", "-").toLowerCase();
  if (normalized === "zh-cn" || normalized === "zh-sg" || normalized.startsWith("zh-hans")) return "zh-CN";
  if (normalized === "zh-tw" || normalized === "zh-hk" || normalized === "zh-mo" || normalized.startsWith("zh-hant")) return "zh-TW";
  if (normalized.startsWith("es")) return "es";
  if (normalized.startsWith("ja") || normalized.startsWith("ko")) return "en";
  if (normalized.startsWith("en")) return "en";
  return null;
}

function readLocalePreference(): SupportedLocale | null {
  const cookie = document.cookie.split(";").map((item) => item.trim()).find((item) => item.startsWith(`${LOCALE_COOKIE}=`));
  if (!cookie) return null;
  return normalizeLocale(decodeURIComponent(cookie.slice(LOCALE_COOKIE.length + 1)));
}

function writeLocalePreference(locale: SupportedLocale): void {
  document.cookie = `${LOCALE_COOKIE}=${encodeURIComponent(locale)}; Max-Age=31536000; Path=/; SameSite=Lax`;
}

function detectLocale(): SupportedLocale {
  const stored = readLocalePreference();
  if (stored) return stored;
  return "en";
}

let currentLocale: SupportedLocale = typeof window === "undefined" ? "en" : detectLocale();

export function getLocale(): SupportedLocale {
  return currentLocale;
}

export function supportedLocales(): readonly SupportedLocale[] {
  return ["zh-CN", "zh-TW", "en", "es"] as const;
}

export function t(key: MessageKey, variables: Record<string, string | number> = {}): string {
  const template = CATALOG[currentLocale][key] ?? ENGLISH[key];
  return Object.entries(variables).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function translateCanonical(source: string): string {
  const trimmed = source.trim();

  const exactOverlay = currentLocale === "zh-CN"
    ? ZH_CN_EXACT
    : currentLocale === "zh-TW"
      ? ZH_TW_EXACT
      : currentLocale === "es"
        ? ES_EXACT
        : null;
  const exactLocalized = exactOverlay?.[trimmed];
  if (exactLocalized) return exactLocalized;

  if (currentLocale === "zh-CN") {

    const next = /^Next:\s*(.+)$/.exec(trimmed);
    if (next?.[1]) return `下一步：${translateCanonical(next[1])}`;

    const countPatterns: Array<[RegExp, (matches: RegExpExecArray) => string]> = [
      [/^(\d+) active · (\d+) voided$/, (m) => `${m[1]} 笔有效 · ${m[2]} 笔作废`],
      [/^(\d+) expected · (\d+) cancelled$/, (m) => `${m[1]} 项预计到账 · ${m[2]} 项已取消`],
      [/^(\d+) opportunities?$/, (m) => `${m[1]} 个融资机会`],
      [/^(\d+) items?$/, (m) => `${m[1]} 项`],
      [/^(\d+) investors?$/, (m) => `${m[1]} 个投资人`],
      [/^(\d+) pending$/, (m) => `${m[1]} 项待处理`],
      [/^(\d+) scheduled$/, (m) => `${m[1]} 项已安排`],
      [/^(\d+) documents?$/, (m) => `${m[1]} 份材料`],
      [/^(\d+) open$/, (m) => `${m[1]} 项未完成`],
      [/^(\d+) outcomes?$/, (m) => `${m[1]} 个融资结果`],
      [/^(\d+) events?$/, (m) => `${m[1]} 条事件`],
      [/^(\d+) receipts?$/, (m) => `${m[1]} 笔到账`],
      [/^(\d+) links?$/, (m) => `${m[1]} 条关联`],
    ];
    for (const [pattern, render] of countPatterns) {
      const match = pattern.exec(trimmed);
      if (match) return render(match);
    }
  }

  if (currentLocale === "zh-TW") {
    const next = /^Next:\s*(.+)$/.exec(trimmed);
    if (next?.[1]) return `下一步：${translateCanonical(next[1])}`;
    const countPatterns: Array<[RegExp, (matches: RegExpExecArray) => string]> = [
      [/^(\d+) active · (\d+) voided$/, (m) => `${m[1]} 筆有效 · ${m[2]} 筆作廢`],
      [/^(\d+) expected · (\d+) cancelled$/, (m) => `${m[1]} 項預計到帳 · ${m[2]} 項已取消`],
      [/^(\d+) opportunities?$/, (m) => `${m[1]} 個融資機會`],
      [/^(\d+) items?$/, (m) => `${m[1]} 項`],
      [/^(\d+) investors?$/, (m) => `${m[1]} 個投資人`],
      [/^(\d+) pending$/, (m) => `${m[1]} 項待處理`],
      [/^(\d+) scheduled$/, (m) => `${m[1]} 項已安排`],
      [/^(\d+) documents?$/, (m) => `${m[1]} 份資料`],
      [/^(\d+) open$/, (m) => `${m[1]} 項未完成`],
      [/^(\d+) outcomes?$/, (m) => `${m[1]} 個融資結果`],
      [/^(\d+) events?$/, (m) => `${m[1]} 筆事件`],
      [/^(\d+) receipts?$/, (m) => `${m[1]} 筆到帳`],
      [/^(\d+) links?$/, (m) => `${m[1]} 條關聯`],
    ];
    for (const [pattern, render] of countPatterns) {
      const match = pattern.exec(trimmed);
      if (match) return render(match);
    }
  }

  if (currentLocale === "es") {
    const next = /^Next:\s*(.+)$/.exec(trimmed);
    if (next?.[1]) return `Siguiente: ${translateCanonical(next[1])}`;
    const countPatterns: Array<[RegExp, (matches: RegExpExecArray) => string]> = [
      [/^(\d+) active · (\d+) voided$/, (m) => `${m[1]} activos · ${m[2]} anulados`],
      [/^(\d+) expected · (\d+) cancelled$/, (m) => `${m[1]} esperados · ${m[2]} cancelados`],
      [/^(\d+) opportunities?$/, (m) => `${m[1]} oportunidades`],
      [/^(\d+) items?$/, (m) => `${m[1]} elementos`],
      [/^(\d+) investors?$/, (m) => `${m[1]} inversores`],
      [/^(\d+) pending$/, (m) => `${m[1]} pendientes`],
      [/^(\d+) scheduled$/, (m) => `${m[1]} programadas`],
      [/^(\d+) documents?$/, (m) => `${m[1]} documentos`],
      [/^(\d+) open$/, (m) => `${m[1]} abiertos`],
      [/^(\d+) outcomes?$/, (m) => `${m[1]} resultados`],
      [/^(\d+) events?$/, (m) => `${m[1]} eventos`],
      [/^(\d+) receipts?$/, (m) => `${m[1]} cobros`],
      [/^(\d+) links?$/, (m) => `${m[1]} vínculos`],
    ];
    for (const [pattern, render] of countPatterns) {
      const match = pattern.exec(trimmed);
      if (match) return render(match);
    }
  }

  const key = englishToKey.get(trimmed);
  if (key) return t(key);

  const blockerCount = /^(\d+) blockers?$/.exec(trimmed);
  if (blockerCount) {
    const count = Number(blockerCount[1]);
    if (currentLocale === "zh-CN") return `${count} 个阻碍`;
    if (currentLocale === "zh-TW") return `${count} 個阻礙`;
    if (currentLocale === "ja") return `${count} 件の阻害要因`;
    if (currentLocale === "ko") return `장애요인 ${count}개`;
    if (currentLocale === "es") return `${count} ${count === 1 ? "bloqueo" : "bloqueos"}`;
  }

  const activeCount = /^(\d+) active$/.exec(trimmed);
  if (activeCount) {
    const count = activeCount[1];
    if (currentLocale === "zh-CN") return `${count} 项进行中`;
    if (currentLocale === "zh-TW") return `${count} 項進行中`;
    if (currentLocale === "ja") return `${count} 件進行中`;
    if (currentLocale === "ko") return `${count}개 진행 중`;
    if (currentLocale === "es") return `${count} en curso`;
  }

  const stepCount = /^(\d+) of (\d+) steps complete$/.exec(trimmed);
  if (stepCount) {
    const [, completed, total] = stepCount;
    if (currentLocale === "zh-CN") return `已完成 ${completed}/${total} 步`;
    if (currentLocale === "zh-TW") return `已完成 ${completed}/${total} 步`;
    if (currentLocale === "ja") return `${total} ステップ中 ${completed} 完了`;
    if (currentLocale === "ko") return `${total}단계 중 ${completed}단계 완료`;
    if (currentLocale === "es") return `${total} pasos: ${completed} completados`;
  }

  return source;
}

function translateTextNode(node: Text): void {
  const original = textSources.get(node) ?? node.data;
  if (!textSources.has(node)) textSources.set(node, original);
  const trimmed = original.trim();
  if (!trimmed) return;
  const localized = translateCanonical(trimmed);
  if (localized === trimmed && currentLocale === "en") {
    node.data = original;
    return;
  }
  const prefix = original.match(/^\s*/)?.[0] ?? "";
  const suffix = original.match(/\s*$/)?.[0] ?? "";
  node.data = `${prefix}${localized}${suffix}`;
}

function translateAttributes(element: Element): void {
  const attributes = ["placeholder", "aria-label", "title", "data-module-label"] as const;
  let sources = attributeSources.get(element);
  if (!sources) {
    sources = new Map<string, string>();
    attributeSources.set(element, sources);
  }
  for (const attribute of attributes) {
    if (!element.hasAttribute(attribute)) continue;
    const current = element.getAttribute(attribute) ?? "";
    const original = sources.get(attribute) ?? current;
    if (!sources.has(attribute)) sources.set(attribute, original);
    element.setAttribute(attribute, translateCanonical(original));
  }
}

export function applyTranslations(root: ParentNode = document): void {
  document.documentElement.lang = currentLocale;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node as Text);
    node = walker.nextNode();
  }
  if (root instanceof Element) translateAttributes(root);
  root.querySelectorAll?.("*").forEach((element) => translateAttributes(element));
}

export function setLocale(locale: SupportedLocale): void {
  if (!CATALOG[locale]) return;
  currentLocale = locale;
  writeLocalePreference(locale);
  applyTranslations(document);
  listeners.forEach((listener) => listener(locale));
}

export function onLocaleChange(listener: (locale: SupportedLocale) => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function formatLocalDate(value: Date): string {
  return new Intl.DateTimeFormat(currentLocale).format(value);
}

export function formatLocalDateTime(value: Date): string {
  return new Intl.DateTimeFormat(currentLocale, { dateStyle: "medium", timeStyle: "short" }).format(value);
}

